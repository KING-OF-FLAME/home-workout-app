"""Packs rendered frames into WebP sprite sheets for the app and writes the manifest.

Usage: python3 pack.py <frames.json> <render out dir> <repo root>
Writes assets/humans/<sex>/<id>.webp, assets/humans/<sex>/thumbs/<id>.webp
and src/data/humanSprites.ts.
"""
import json, os, sys
from PIL import Image

frames_json, render_dir, repo = sys.argv[1:4]
DATA = json.load(open(frames_json))['moves']
FW, FH = 400, 300  # frame size in the sheet
COLS = 5
TW, TH = 200, 150  # list thumbnail

manifest = {}
requires = {'male': [], 'female': []}
thumbs = {'male': [], 'female': []}
for sex in ('male', 'female'):
    out = os.path.join(repo, 'assets', 'humans', sex)
    os.makedirs(os.path.join(out, 'thumbs'), exist_ok=True)
    for mid, move in DATA.items():
        d = os.path.join(render_dir, sex, mid)
        n = len(move['frames'])
        files = [os.path.join(d, f'{i:02d}.png') for i in range(n)]
        if not all(os.path.exists(f) for f in files):
            print('missing frames', sex, mid)
            continue
        rows = (n + COLS - 1) // COLS
        sheet = Image.new('RGB', (COLS * FW, rows * FH), (12, 13, 16))
        for i, f in enumerate(files):
            im = Image.open(f).convert('RGB').resize((FW, FH), Image.LANCZOS)
            sheet.paste(im, ((i % COLS) * FW, (i // COLS) * FH))
        sheet.save(os.path.join(out, f'{mid}.webp'), 'WEBP', quality=74, method=6)
        # Thumbnail: the frame furthest into the move (usually the hardest position).
        ti = n // 2 if move['view'] == 'side' else n // 3
        Image.open(files[ti]).convert('RGB').resize((TW, TH), Image.LANCZOS).save(os.path.join(out, 'thumbs', f'{mid}.webp'), 'WEBP', quality=72, method=6)
        cues = []
        for fr in move['frames']:
            cues.append(fr.get('cue') or '')
        manifest[mid] = {'n': n, 'ms': round(move['ms']), 'cues': cues}
        requires[sex].append(mid)
        thumbs[sex].append(mid)

ids = sorted(manifest)
lines = [
    '// Generated by tools/render-humans/pack.py. Do not edit by hand.',
    '// Realistic exercise demos rendered in Blender from MakeHuman bodies (CC0 assets).',
    '/* eslint-disable @typescript-eslint/no-require-imports */',
    '',
    f'export const HUMAN_FRAME = {{ w: {FW}, h: {FH}, cols: {COLS} }} as const;',
    '',
    'export interface HumanMove {',
    '  /** Frames in the loop. */',
    '  n: number;',
    '  /** Loop length at normal speed, in ms. */',
    '  ms: number;',
    '  /** Coaching cue per frame. */',
    '  cues: string[];',
    '}',
    '',
    'export const HUMAN_MOVES: Record<string, HumanMove> = {',
]
for mid in ids:
    lines.append(f'  {json.dumps(mid)}: {json.dumps(manifest[mid], ensure_ascii=False)},')
lines.append('};')
lines.append('')
for kind, src, sub in (('HUMAN_SHEETS', requires, ''), ('HUMAN_THUMBS', thumbs, 'thumbs/')):
    lines.append(f'export const {kind}: Record<"male" | "female", Record<string, number>> = {{')
    for sex in ('male', 'female'):
        lines.append(f'  {sex}: {{')
        for mid in sorted(src[sex]):
            lines.append(f"    {json.dumps(mid)}: require('../../assets/humans/{sex}/{sub}{mid}.webp'),")
        lines.append('  },')
    lines.append('};')
    lines.append('')
open(os.path.join(repo, 'src', 'data', 'humanSprites.ts'), 'w').write('\n'.join(lines))
total = sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(os.path.join(repo, 'assets', 'humans')) for f in fs)
print(f'packed {len(ids)} moves, {total / 1e6:.1f} MB')
